// ── Core functions
function getLang() {
  return localStorage.getItem('witlab_lang') || 'en';
}

function setLang(lang) {
  localStorage.setItem('witlab_lang', lang);
  applyLang(lang);
}

function applyLang(lang) {
  if (!lang) lang = getLang();
  const t = I18N[lang] || I18N.en;

  // text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  // placeholders
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.dataset.i18nPh;
    if (t[key] !== undefined) el.placeholder = t[key];
  });
  // active lang button
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  // html lang attr
  document.documentElement.lang = lang;
}

// ── Language switcher HTML (injected into nav)
function buildLangSwitcher() {
  return `<div class="lang-switcher">
    <button class="lang-btn" data-lang="en"  onclick="setLang('en')">EN</button>
    <button class="lang-btn" data-lang="ko"  onclick="setLang('ko')">한</button>
    <button class="lang-btn" data-lang="ja"  onclick="setLang('ja')">日</button>
    <button class="lang-btn" data-lang="zh"  onclick="setLang('zh')">中</button>
  </div>`;
}

